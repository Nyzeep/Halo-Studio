#!/usr/bin/env node
/**
 * Bare-value style check (M4, ADR-0077; issue #53).
 *
 * Web equivalent of the DMS "Theme singleton, no hard-coded values" rule:
 * component styles must reference design tokens (src/tokens/tokens.css) via
 * var(--…) instead of raw color literals or raw px spacing/radius values.
 *
 * Scanned value classes:
 *   - color literals: #hex (3/4/6/8 digits), rgb()/rgba()/hsl()/hsla();
 *   - px values in spacing/radius declarations: padding*, margin*, gap*,
 *     border-radius*;
 *   - raw px values inside custom property definitions (token laundering
 *     guard), except in src/tokens/ where raw values are the point.
 *
 * Exemptions: the pre-existing legacy style files (317 .scss + the older
 * .css files) are listed in style-token-exemptions.mjs. That list is
 * GENERATED and must only ever shrink (files removed from the repo or
 * rewritten as clean .module.css); it must never grow. New or rewritten style
 * files are not exempt and fail this check until they reference tokens.
 *
 * Usage:
 *   node scripts/check-style-tokens.mjs                       # check
 *   node scripts/check-style-tokens.mjs --regenerate-exemptions
 */

import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, sep } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const webUiRoot = dirname(scriptDir);
const srcRoot = join(webUiRoot, 'src');
const tokensRoot = join(srcRoot, 'tokens');
const exemptionFile = join(scriptDir, 'style-token-exemptions.mjs');
const EXEMPTION_HEADER = [
  '/**',
  ' * GENERATED by scripts/check-style-tokens.mjs --regenerate-exemptions — DO NOT EDIT BY HAND.',
  ' *',
  ' * Bare-value exemption list for the legacy style files (issue #53, M4):',
  ' * every entry is a pre-existing .scss/.css file that predates the token',
  ' * layer (ADR-0077). The list is "only shrink" (只减不增): entries may be',
  ' * removed when a file is deleted or rewritten as a clean CSS Module, but',
  ' * new files must never be added — they are required to reference tokens.',
  ' */',
].join('\n');

const regenerate = process.argv.includes('--regenerate-exemptions');

function listStyleFiles(root, prefix = '') {
  const files = [];
  for (const entry of readdirSync(root)) {
    const absolute = join(root, entry);
    const relative = prefix ? posix.join(prefix, entry) : entry;
    if (statSync(absolute).isDirectory()) {
      if (absolute === tokensRoot) {
        // src/tokens/ is the token definition layer: raw values live there.
        continue;
      }
      files.push(...listStyleFiles(absolute, relative));
      continue;
    }
    if (/\.(css|scss)$/.test(entry)) {
      files.push(relative);
    }
  }
  return files.sort();
}

function stripComments(source) {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|\s)\/\/.*$/gm, '$1');
}

const COLOR_LITERAL_PATTERNS = [
  /#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{4}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})\b/,
  /\b(?:rgba?|hsla?)\(\s*-?[\d.]+/,
];

const SPACING_PROPERTY_PATTERN = /\b(?:padding|margin|gap)(?:-(?:top|right|bottom|left|inline|block|start|end))?\s*:/;
const RADIUS_PROPERTY_PATTERN = /\bborder-radius(?:-(?:top-left|top-right|bottom-left|bottom-right))?\s*:/;
const CUSTOM_PROPERTY_PATTERN = /^\s*--[\w-]+\s*:/;
const PX_VALUE_PATTERN = /(?:^|[\s,(])(?:-?\d*\.?\d+)px\b/;

function findViolations(source) {
  const violations = [];
  const lines = stripComments(source).split('\n');
  for (let lineIndex = 0; lineIndex < lines.length; lineIndex += 1) {
    const line = lines[lineIndex];
    if (line.trim().length === 0) {
      continue;
    }

    for (const pattern of COLOR_LITERAL_PATTERNS) {
      if (pattern.test(line)) {
        violations.push({ line: lineIndex + 1, reason: 'raw color literal', text: line.trim() });
        break;
      }
    }

    const isSpacingOrRadius = SPACING_PROPERTY_PATTERN.test(line) || RADIUS_PROPERTY_PATTERN.test(line);
    const isCustomPropertyDefinition = CUSTOM_PROPERTY_PATTERN.test(line);
    if ((isSpacingOrRadius || isCustomPropertyDefinition) && PX_VALUE_PATTERN.test(line)) {
      violations.push({
        line: lineIndex + 1,
        reason: isSpacingOrRadius
          ? 'raw px spacing/radius value'
          : 'raw px value in custom property definition',
        text: line.trim(),
      });
    }
  }
  return violations;
}

async function readExemptions() {
  if (!existsSync(exemptionFile)) {
    return [];
  }
  const module = await import(pathToFileURL(exemptionFile).href);
  return module.default;
}

function writeExemptions(files) {
  const body = `${EXEMPTION_HEADER}\n\nexport default ${JSON.stringify(files, null, 2)};\n`;
  writeFileSync(exemptionFile, body);
}

const allStyleFiles = listStyleFiles(srcRoot);

if (regenerate) {
  writeExemptions(allStyleFiles);
  console.log(`[check-style-tokens] regenerated ${exemptionFile} with ${allStyleFiles.length} entries.`);
  process.exit(0);
}

const exemptions = (await readExemptions());
const exemptionSet = new Set(exemptions);

let failed = false;

// The exemption list must only shrink: every entry still has to exist, and
// generation-time files that disappeared must be pruned via regeneration.
const staleEntries = exemptions.filter(entry => !existsSync(join(srcRoot, entry)));
if (staleEntries.length > 0) {
  failed = true;
  console.error('[check-style-tokens] stale exemption entries (files deleted or rewritten):');
  for (const entry of staleEntries) {
    console.error(`  - ${entry}`);
  }
  console.error('Regenerate with: node scripts/check-style-tokens.mjs --regenerate-exemptions');
}

for (const relativePath of allStyleFiles) {
  if (exemptionSet.has(relativePath)) {
    continue;
  }
  const absolutePath = join(srcRoot, relativePath);
  const violations = findViolations(readFileSync(absolutePath, 'utf8'));
  if (violations.length === 0) {
    continue;
  }
  failed = true;
  console.error(`[check-style-tokens] ${relativePath}: bare values are not allowed (use var(--token) from src/tokens/)`);
  for (const violation of violations) {
    console.error(`  line ${violation.line}: ${violation.reason}`);
    console.error(`    ${violation.text}`);
  }
}

if (failed) {
  process.exit(1);
}

console.log(
  `[check-style-tokens] OK — ${allStyleFiles.length} style files scanned, ` +
  `${exemptions.length} legacy exemptions, ${allStyleFiles.length - exemptionSet.size} token-checked.`,
);
